package website

import com.varabyte.kobwebx.gradle.markdown.children
import com.varabyte.kobwebx.gradle.markdown.handlers.MarkdownHandlers
import com.varabyte.kobwebx.gradle.markdown.handlers.NodeScope
import org.commonmark.ext.gfm.tables.TableBlock
import org.commonmark.ext.gfm.tables.TableBody
import org.commonmark.ext.gfm.tables.TableCell
import org.commonmark.ext.gfm.tables.TableHead
import org.commonmark.ext.gfm.tables.TableRow
import org.commonmark.node.*
import org.gradle.api.GradleException

/** Doc placeholders like `{{kore.release}}`, listed in the "Documentation pages" section of `contributing/Architecture_and_Patterns.md`. */
internal val docConstantRegex = Regex("""\{\{((?:java|kore|mc)\.\w+)}}""")

/** `kore.release` -> `koreRelease`, its property in the generated `DocConstants`. */
internal fun docConstantProperty(key: String) = key.split('.').let { (prefix, name) -> prefix + name.replaceFirstChar { it.uppercase() } }

/** Ordered so "GitHub Actions" wins over "GitHub". */
private val brandIcons = listOf(
	"CurseForge" to "curseforge",
	"GitHub Actions" to "githubactions",
	"GitHub" to "github",
	"Gradle" to "gradle",
	"IntelliJ" to "intellijidea",
	"Modrinth" to "modrinth",
	"Node.js" to "nodedotjs",
)

private val headingIdSeparator = Regex("[^a-z0-9]+")
private val lineBreakTag = Regex("""<br\s*/?>""")

/**
 * Turns each top-level block of a doc page into one `DocView(DocNode...)` expression, drawn by `DocView` in the site, and expands the doc placeholders.
 * A node the site can't draw fails the build, there is no fallback renderer.
 */
fun MarkdownHandlers.useSiteComponents() {
	val block: NodeScope.(Node) -> String = {
		childrenOverride = emptyList()
		"DocView(${docNode(it)})"
	}

	blockquote.set(block)
	code.set(block)
	heading.set(block)
	hr.set(block)
	html.set(block)
	ol.set(block)
	p.set(block)
	table.set(block)
	ul.set(block)
}

/** Placeholders become templates reading the `DocConstants` generated by `kobwebxMarkdownProcess`, once the release data is fetched. */
private fun String.withDocConstants() = replace(docConstantRegex) { "\${io.github.ayfri.kore.website.DocConstants.${docConstantProperty(it.groupValues[1])}}" }

private fun Node.plainText(): String = when (this) {
	is Code -> literal
	is Emphasis, is Heading, is Link, is StrongEmphasis -> children().joinToString("") { it.plainText() }
	is Text -> literal
	else -> ""
}

/** A Kotlin string literal of [text], escaped first so the placeholders it holds can become templates. */
private fun MarkdownHandlers.lit(text: String) = "\"${text.escapeSingleQuotedText().withDocConstants()}\""

/** `, child, child`, the arguments completing a `DocNode` constructor. A tight list item holds its text in a paragraph that is spliced away, as Kobweb does. */
private fun MarkdownHandlers.docChildren(parent: Node): String = parent.children().joinToString("") {
	if (it is Paragraph && (it.parent?.parent as? ListBlock)?.isTight == true) docChildren(it) else ", ${docNode(it)}"
}

private fun MarkdownHandlers.tag(name: String, node: Node) = "DocElement(\"$name\"${docChildren(node)})"

/** Removes the `[!TYPE]` marker from a blockquote and returns `TYPE`, or null when the blockquote isn't a callout. */
private fun BlockQuote.takeCalloutType(): String? {
	val paragraph = firstChild as? Paragraph ?: return null
	val text = paragraph.firstChild as? Text ?: return null
	if (!text.literal.startsWith("[!")) return null

	val type = text.literal.substringAfter("[!").substringBefore("]").uppercase()
	val remaining = text.literal.substringAfter("]").trim()
	if (remaining.isNotEmpty()) {
		text.literal = remaining
		return type
	}

	text.unlink()
	if (paragraph.firstChild == null) paragraph.unlink()
	return type
}

private fun Node.unsupported(what: String? = this::class.simpleName): Nothing {
	val title = generateSequence(this) { it.parent }.last().children().filterIsInstance<Heading>().firstOrNull { it.level == 1 }?.plainText()
	val line = generateSequence(this) { it.parent }.firstNotNullOfOrNull { it.sourceSpans.firstOrNull() }?.lineIndex?.plus(1)
	throw GradleException("Doc pages don't support $what (line $line of \"$title\")")
}

private fun MarkdownHandlers.docNode(node: Node): String = when (node) {
	is BlockQuote -> node.takeCalloutType()?.let { "DocCallout(${lit(it)}${docChildren(node)})" } ?: tag("blockquote", node)
	is BulletList -> tag("ul", node)
	is Code -> "DocCode(${lit(node.literal)})"
	is Emphasis -> tag("em", node)
	is FencedCodeBlock -> {
		/** Kobweb turns a top-level indented code block into a fence without `info`. */
		val lang = node.info?.takeIf { it.isNotBlank() }?.let { lit(it) } ?: "null"
		"DocCodeBlock(\"\"\"${node.literal.escapeTripleQuotedText().withDocConstants()}\"\"\", $lang)"
	}

	is HardLineBreak -> tag("br", node)
	is Heading -> {
		val id = node.children().joinToString("") {
			it.plainText().takeIf { text -> text.isNotBlank() }?.lowercase()?.replace(headingIdSeparator, "-").orEmpty()
		}.trim('-')
		val headingText = node.plainText()
		val icon = brandIcons.firstOrNull { (brand) -> brand in headingText }?.let { (_, icon) -> "\"$icon\"" }
		"DocHeading(${node.level}, \"$id\", $icon${docChildren(node)})"
	}

	is HtmlInline -> if (lineBreakTag.matches(node.literal)) tag("br", node) else node.unsupported("the inline HTML ${node.literal}")
	is Image -> {
		val alt = node.children().joinToString("") { it.plainText() }
		if (node.destination.startsWith("mc:")) "DocSprite(${lit(node.destination.removePrefix("mc:"))}, ${lit(alt)})"
		else "DocImage(${lit(node.destination)}, ${lit(alt)})"
	}

	is Link -> if (node.destination.substringBefore('#').endsWith(".md") && "://" !in node.destination) {
		node.unsupported("the relative link ${node.destination}, link its /docs route")
	} else "DocLink(${lit(node.destination)}${docChildren(node)})"
	is ListItem -> tag("li", node)
	is OrderedList -> tag("ol", node)
	is Paragraph -> tag("p", node)
	is StrongEmphasis -> tag("b", node)
	is TableBlock -> tag("table", node)
	is TableBody -> tag("tbody", node)
	is TableCell -> {
		val cellTag = if (node.isHeader) "th" else "td"
		node.alignment?.let { "DocCell(\"$cellTag\", ${lit(it.name.lowercase())}${docChildren(node)})" } ?: tag(cellTag, node)
	}

	is TableHead -> tag("thead", node)
	is TableRow -> tag("tr", node)
	is Text -> "DocText(${lit(node.literal)})"
	is ThematicBreak -> tag("hr", node)
	else -> node.unsupported()
}
